/**
 * \author Mr.Nobody
 * \file Pka_Curves.c
 * \ingroup Pka
 * \brief Predefined NIST elliptic curves (FIPS 186-4, Digital Signature Standard).
 *
 * The coefficient `a` of every NIST prime curve equals -3; it is written with the
 * \ref PKA_SIGN_NEGATIVE representation (RM0481/492/517, PKA chapter, section 41.6.1,
 * option 2), so the stored absolute value is 3 instead of p-3. Each byte table is
 * built with a `#define` (standard preprocessor line continuation) instead of a
 * plain multi-line initializer, so the curve domain parameters stay in one place
 * next to their own name, as named data, with the real values spelled out in full.
 *
 * \note Only P-256 and P-384 are predefined here; both constant sets were verified
 *       against the defining formula of p and against the base point lying on the
 *       curve. P-521 (and the Brainpool family the README also mentions) is not
 *       predefined to avoid shipping a 521-bit constant that could not be verified
 *       the same way within this change; an application can still build its own
 *       \ref pka_Curve_t for it, the module itself supports any curve.
 *
 */
